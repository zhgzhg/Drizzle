package com.github.zhgzhg.drizzle.remote;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.AtomicMoveNotSupportedException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.Paths;
import java.nio.file.StandardCopyOption;
import java.nio.file.attribute.PosixFilePermissions;
import java.util.Arrays;
import java.util.Locale;

/**
 * Writes a script at a fixed per-user location that starts the Drizzle CLI with the Java runtime of the running
 * Arduino IDE, so the CLI can be found and run without knowing where the IDE is installed.
 */
public final class Launcher {
    private Launcher() { }

    public static Path defaultDirectory() {
        return Paths.get(System.getProperty("user.home"), ".drizzle", "bin");
    }

    public static boolean isWindows() {
        return System.getProperty("os.name", "").toLowerCase(Locale.ROOT).startsWith("windows");
    }

    /**
     * @return the java executable of the given Java home ({@code java.home})
     */
    public static Path javaExecutable(final Path javaHome) {
        return javaHome.resolve("bin").resolve(isWindows() ? "java.exe" : "java");
    }

    /**
     * Writes {@code drizzle.cmd} on Windows, or an executable {@code drizzle} shell script elsewhere. The file is only
     * replaced when its content changes, and then atomically, so a CLI call running from it isn't disturbed.
     *
     * @return the script
     */
    public static Path write(final Path binDir, final Path javaExecutable, final Path jar, final String drizzleVersion)
            throws IOException {
        Files.createDirectories(binDir);

        if (isWindows()) {
            Path script = binDir.resolve("drizzle.cmd");
            writeIfChanged(script, windowsScript(javaExecutable.toString(), jar.toString(), drizzleVersion)
                    .getBytes(StandardCharsets.UTF_8), false);
            return script;
        }

        Path script = binDir.resolve("drizzle");
        writeIfChanged(script, posixScript(javaExecutable.toString(), jar.toString(), drizzleVersion)
                .getBytes(StandardCharsets.UTF_8), true);
        return script;
    }

    /**
     * cmd.exe reads batch files in the console's code page, so non-ASCII paths only survive when the script
     * switches the console to UTF-8 first (the file is UTF-8). The original code page is restored afterwards.
     */
    static String windowsScript(final String javaExecutable, final String jar, final String drizzleVersion) {
        String header = "@echo off\r\n"
                + "rem Generated by Drizzle " + drizzleVersion + " when Arduino IDE started. Runs the Drizzle CLI.\r\n";
        String run = "\"" + escapeCmd(javaExecutable) + "\" -jar \"" + escapeCmd(jar) + "\" %*\r\n";

        if (isAscii(javaExecutable) && isAscii(jar)) {
            return header + run; // the java line stays last, so the script exits with java's exit code
        }

        return header
                + "setlocal\r\n"
                + "for /f \"tokens=2 delims=:.\" %%c in ('chcp') do set \"DRIZZLE_CP=%%c\"\r\n"
                + "chcp 65001 >nul\r\n"
                + run
                + "set \"DRIZZLE_EXIT=%ERRORLEVEL%\"\r\n"
                + "if defined DRIZZLE_CP chcp %DRIZZLE_CP% >nul\r\n"
                + "exit /b %DRIZZLE_EXIT%\r\n";
    }

    static String posixScript(final String javaExecutable, final String jar, final String drizzleVersion) {
        return "#!/bin/sh\n"
                + "# Generated by Drizzle " + drizzleVersion + " when Arduino IDE started. Runs the Drizzle CLI.\n"
                + "exec " + quoteSh(javaExecutable) + " -jar " + quoteSh(jar) + " \"$@\"\n";
    }

    private static void writeIfChanged(final Path file, final byte[] content, final boolean executable) throws IOException {
        if (Files.isRegularFile(file) && Arrays.equals(Files.readAllBytes(file), content)) {
            return;
        }

        Path tmp = Files.createTempFile(file.getParent(), file.getFileName().toString(), ".tmp");
        try {
            Files.write(tmp, content);
            if (executable) {
                try {
                    Files.setPosixFilePermissions(tmp, PosixFilePermissions.fromString("rwxr-xr-x"));
                } catch (UnsupportedOperationException e) {
                    // not a POSIX file system - nothing to mark as executable
                }
            }
            try {
                Files.move(tmp, file, StandardCopyOption.ATOMIC_MOVE, StandardCopyOption.REPLACE_EXISTING);
            } catch (AtomicMoveNotSupportedException e) {
                Files.move(tmp, file, StandardCopyOption.REPLACE_EXISTING);
            }
        } finally {
            Files.deleteIfExists(tmp);
        }
    }

    private static boolean isAscii(final String s) {
        return s.chars().allMatch(c -> c < 0x80);
    }

    private static String escapeCmd(final String s) {
        return s.replace("%", "%%");
    }

    private static String quoteSh(final String s) {
        return "'" + s.replace("'", "'\\''") + "'";
    }
}
